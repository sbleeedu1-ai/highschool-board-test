-- 공지 표. 시각은 UTC로 저장한다. 수정일시는 수정한 적이 없으면 비워 둔다.
-- H2(PostgreSQL 호환 모드)와 실제 PostgreSQL에서 모두 돌아가는 문법만 쓴다.
CREATE TABLE notice (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title      VARCHAR(100)             NOT NULL,
    body       VARCHAR(5000)            NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE
);

-- 공지 목록 정렬(작성일시 내림차순, 같으면 식별자 내림차순)에 쓰는 색인
CREATE INDEX idx_notice_created_at_id ON notice (created_at DESC, id DESC);
